#!/usr/bin/env python3
"""
Write the productKey from a 1W remote's QR code (e.g. Somfy Situo) into include/iown_key.h.

Only the analysis tools use it (scripts/Iown-Decode.py --key-header checks the MACs
of sniffed remote frames); the firmware does not. The QR payload is read from a
file, and the key is written only into the git-ignored header, never printed.
An existing controller identity block (scripts/Iown-GenController.py) is kept.

Usage: Iown-GenKeyHeader.py <qr payload file> <output header path>
"""

import re
import sys


def parse_qr(path):
  raw = open(path).read()
  qr = "".join(c for c in raw if c in "0123456789abcdefABCDEF")
  if len(qr) != 56:
    sys.exit(f"QR payload: expected 56 hex chars, got {len(qr)}")
  return bytes.fromhex(qr[2:8]), bytes.fromhex(qr[8:40])


def main(args):
  if len(args) != 3:
    sys.exit(__doc__)
  qr_node, product_key = parse_qr(args[1])

  def c_array(b):
    return "{ " + ", ".join(f"0x{x:02X}" for x in b) + " }"

  header = f"""// GENERATED by scripts/Iown-GenKeyHeader.py - DO NOT COMMIT (git-ignored)
// 1W secrets for this installation.
#pragma once

// Remote's QR productKey (remote address {qr_node.hex().upper()}); used only by the analysis
// scripts, e.g. scripts/Iown-Decode.py --key-header to check sniffed MACs
#define IOWN_PRODUCT_KEY {c_array(product_key)} // {len(product_key)} bytes
"""
  # keep the LoRa32's own controller identity (scripts/Iown-GenController.py) if present
  try:
    old = open(args[2]).read()
    m = re.search(r"// BEGIN controller identity.*?// END controller identity\n?", old, re.S)
    if m:
      header += "\n" + m.group(0)
      print("kept the existing controller identity block")
  except FileNotFoundError:
    pass
  with open(args[2], "w") as f:
    f.write(header)
  print(f"wrote {args[2]} (remote {qr_node.hex()}, key not shown)")


if __name__ == "__main__":
  main(sys.argv)
